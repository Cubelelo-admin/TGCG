// Stretches GPX routes to their official distance.
// Out-and-back routes: the U-turn point is pushed further along the road (both legs grow equally).
// Loops with no U-turn: the last point (finish) is extended along the final stretch.
// Originals are kept in gpx/original/.
// Run: node course-map-tools/fix-distance.js
const fs = require("fs"), path = require("path");
const GPX = path.join(__dirname, "..", "public", "events", "raipur", "course-map", "gpx"); // live GPX
const ORIG = path.join(__dirname, "gpx", "original"); // private backups (not on the website)
// NOTE: Track A (42K/21K/10K) is now generated by tools/build-tracks.js — do NOT list it here,
// or this script would overwrite it with the old original GPX.
const OFFICIAL = { // file -> official metres
  "6KM Dream Run.gpx": 6000,
};

const R = 6371000, rad = Math.PI / 180;
const hav = (a, b) => { const dLat = (b[0]-a[0])*rad, dLon = (b[1]-a[1])*rad; const s = Math.sin(dLat/2)**2 + Math.cos(a[0]*rad)*Math.cos(b[0]*rad)*Math.sin(dLon/2)**2; return 2*R*Math.asin(Math.sqrt(s)); };
const brg = (a, b) => { const y = Math.sin((b[1]-a[1])*rad)*Math.cos(b[0]*rad); const x = Math.cos(a[0]*rad)*Math.sin(b[0]*rad) - Math.sin(a[0]*rad)*Math.cos(b[0]*rad)*Math.cos((b[1]-a[1])*rad); return Math.atan2(y, x); };
const dest = (p, b, d) => {
  const la = p[0]*rad, lo = p[1]*rad, dr = d / R;
  const la2 = Math.asin(Math.sin(la)*Math.cos(dr) + Math.cos(la)*Math.sin(dr)*Math.cos(b));
  const lo2 = lo + Math.atan2(Math.sin(b)*Math.sin(dr)*Math.cos(la), Math.cos(dr) - Math.sin(la)*Math.sin(la2));
  return [la2/rad, lo2/rad];
};
const total = (p) => p.reduce((s, q, i) => i ? s + hav(p[i-1], q) : 0, 0);
const TRKPT = /<trkpt lat="([-\d.]+)" lon="([-\d.]+)"/g;

fs.mkdirSync(ORIG, { recursive: true });
for (const [file, target] of Object.entries(OFFICIAL)) {
  const fp = path.join(GPX, file), bak = path.join(ORIG, file);
  if (!fs.existsSync(bak)) fs.copyFileSync(fp, bak);
  const xml = fs.readFileSync(bak, "utf8"); // always start from the original
  const pts = [...xml.matchAll(TRKPT)].map((m) => [+m[1], +m[2]]);
  const before = total(pts);

  // U-turns: ~180° reversal, ignoring the tiny one at the finish chute (<150 m from start)
  const uturns = [];
  for (let i = 1; i < pts.length - 1; i++) {
    if (hav(pts[i-1], pts[i]) < 1 || hav(pts[i], pts[i+1]) < 1) continue;
    let d = Math.abs(brg(pts[i-1], pts[i]) - brg(pts[i], pts[i+1])) / rad; d = d % 360; if (d > 180) d = 360 - d;
    if (d > 170 && hav(pts[0], pts[i]) > 150) uturns.push(i);
  }

  // Solve for the extension iteratively (exact even if legs aren't perfectly collinear)
  let ext = (target - before) / (uturns.length ? 2 * uturns.length : 1), moved;
  for (let k = 0; k < 20; k++) {
    moved = pts.map((p) => p.slice());
    if (uturns.length) uturns.forEach((i) => { moved[i] = dest(pts[i], brg(pts[i-1], pts[i]), ext); });
    else { const n = pts.length - 1; moved[n] = dest(pts[n], brg(pts[n-1], pts[n]), ext); }
    const err = target - total(moved);
    if (Math.abs(err) < 0.05) break;
    ext += err / (uturns.length ? 2 * uturns.length : 1);
  }

  let idx = 0;
  const out = xml.replace(TRKPT, () => { const p = moved[idx++]; return `<trkpt lat="${p[0].toFixed(7)}" lon="${p[1].toFixed(7)}"`; });
  fs.writeFileSync(fp, out);
  console.log(`${file}: ${(before/1000).toFixed(4)} -> ${(total(moved)/1000).toFixed(4)} km  ` +
    (uturns.length ? `(U-turn pushed ${ext.toFixed(1)} m at idx ${uturns.join(", ")})` : `(finish extended ${ext.toFixed(1)} m — no U-turn)`));
}
