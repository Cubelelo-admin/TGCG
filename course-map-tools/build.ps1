# Converts every GPX file in the live course map's /gpx folder into its data/routes.js
# Run:  powershell -ExecutionPolicy Bypass -File course-map-tools\build.ps1
# (These tools live outside /public so they are not downloadable from the website.)
$ErrorActionPreference = 'Stop'
$root = Join-Path $PSScriptRoot '..\public\events\raipur\course-map'
$gpxDir = Join-Path $root 'gpx'
$files = @()
if (Test-Path $gpxDir) { $files += Get-ChildItem -LiteralPath $gpxDir -Filter *.gpx }
$files += Get-ChildItem -LiteralPath $root -Filter *.gpx
$inv = [System.Globalization.CultureInfo]::InvariantCulture

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// AUTO-GENERATED by build.ps1 from GPX files. Do not edit by hand.')
[void]$out.AppendLine('window.ROUTES = {')
foreach ($f in $files) {
  $x = [xml](Get-Content -LiteralPath $f.FullName -Raw -Encoding UTF8)
  $pts = $x.GetElementsByTagName('trkpt')
  if ($pts.Count -eq 0) { $pts = $x.GetElementsByTagName('rtept') }
  $coords = foreach ($p in $pts) {
    $lat = [double]::Parse($p.lat, $inv); $lon = [double]::Parse($p.lon, $inv)
    $eleNode = $p.GetElementsByTagName('ele')
    $ele = if ($eleNode.Count) { [double]::Parse($eleNode[0].InnerText, $inv) } else { 0 }
    '[' + $lat.ToString('0.######', $inv) + ',' + $lon.ToString('0.######', $inv) + ',' + $ele.ToString('0.#', $inv) + ']'
  }
  $key = $f.Name
  [void]$out.AppendLine("  `"$key`": [" + ($coords -join ',') + '],')
  Write-Host "$key -> $($pts.Count) points"
}
[void]$out.AppendLine('};')
New-Item -ItemType Directory -Force (Join-Path $root 'data') | Out-Null
[System.IO.File]::WriteAllText((Join-Path $root 'data\routes.js'), $out.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host 'Wrote data/routes.js'
